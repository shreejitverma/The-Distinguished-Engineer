"""gRPC status codes and the google.rpc.Status rich error model, without grpcio-status.

The pinned workspace has `grpcio` and `protobuf` but not `grpcio-status` or
`googleapis-common-protos`, so this module rebuilds the two upstream pieces it needs:

* the `google.rpc` descriptors (field numbers copied from googleapis `google/rpc/status.proto`
  and `google/rpc/error_details.proto`) inside a private `DescriptorPool`, so the real protobuf
  runtime serializes, parses, packs, and unpacks them;
* `to_grpc_status` and `from_trailing_metadata`, the same contract as `grpc_status.rpc_status`
  (`to_status`, `from_call`) in grpcio-status 1.85.1, including its consistency check.

The code tables (library-generated codes, HTTP and RST_STREAM mappings, retryability) are data
copied from grpc `doc/statuscodes.md`, `doc/http-grpc-status-mapping.md`, `doc/PROTOCOL-HTTP2.md`
and AIP-194, so a test can prove them against a real grpcio peer.
"""

from __future__ import annotations

import enum
from dataclasses import dataclass
from typing import TYPE_CHECKING, Any, Final, NamedTuple

import grpc  # type: ignore[import-untyped]
from google.protobuf import (  # type: ignore[import-untyped]
    any_pb2,
    descriptor_pb2,
    descriptor_pool,
    duration_pb2,
    message_factory,
)
from google.protobuf.message import DecodeError  # type: ignore[import-untyped]

if TYPE_CHECKING:
    from collections.abc import Iterable, Mapping

DETAILS_KEY: Final = "grpc-status-details-bin"
"""The reserved trailer for a serialized `google.rpc.Status` (PROTOCOL-HTTP2, Responses)."""

_NAME_BYTES: Final = len(DETAILS_KEY)
_PER_FIELD_OVERHEAD: Final = 32  # RFC 9113 Section 6.5.2 SETTINGS_MAX_HEADER_LIST_SIZE accounting

# --- the 17 canonical codes (OK plus the 16 error codes) ---

StatusCode = grpc.StatusCode
CANONICAL: Final[tuple[Any, ...]] = tuple(sorted(StatusCode, key=lambda code: code.value[0]))


def code_number(code: Any) -> int:
    """The wire integer of a `grpc.StatusCode` (its `value` is `(number, lowercase name)`)."""
    return int(code.value[0])


_BY_NUMBER: Final[Mapping[int, Any]] = {code_number(code): code for code in CANONICAL}


def code_from_number(number: int) -> Any:
    """Map a received integer to a code; values outside 0..16 become UNKNOWN.

    doc/statuscodes.md: libraries that see a value outside the defined range "must either
    propagate them directly or convert them to UNKNOWN".
    """
    return _BY_NUMBER.get(number, StatusCode.UNKNOWN)


# Codes the grpc library itself generates, per the table in doc/statuscodes.md.
LIBRARY_GENERATED: Final = frozenset(
    {
        StatusCode.CANCELLED,
        StatusCode.UNKNOWN,
        StatusCode.DEADLINE_EXCEEDED,
        StatusCode.UNIMPLEMENTED,
        StatusCode.UNAVAILABLE,
        StatusCode.INTERNAL,
        StatusCode.RESOURCE_EXHAUSTED,
        StatusCode.UNAUTHENTICATED,
    }
)
# doc/statuscodes.md: "The following status codes are never generated by the library".
APPLICATION_ONLY: Final = frozenset(
    {
        StatusCode.INVALID_ARGUMENT,
        StatusCode.NOT_FOUND,
        StatusCode.ALREADY_EXISTS,
        StatusCode.FAILED_PRECONDITION,
        StatusCode.ABORTED,
        StatusCode.OUT_OF_RANGE,
        StatusCode.DATA_LOSS,
    }
)

# doc/http-grpc-status-mapping.md: only for a response that carries no grpc-status.
_HTTP_TO_GRPC: Final[Mapping[int, Any]] = {
    400: StatusCode.INTERNAL,
    401: StatusCode.UNAUTHENTICATED,
    403: StatusCode.PERMISSION_DENIED,
    404: StatusCode.UNIMPLEMENTED,
    429: StatusCode.UNAVAILABLE,
    502: StatusCode.UNAVAILABLE,
    503: StatusCode.UNAVAILABLE,
    504: StatusCode.UNAVAILABLE,
}


def code_for_http_status(http_status: int) -> Any:
    """Client-side mapping for a response without `grpc-status`; every other status is UNKNOWN."""
    return _HTTP_TO_GRPC.get(http_status, StatusCode.UNKNOWN)


# doc/PROTOCOL-HTTP2.md, Errors: RST_STREAM error code -> gRPC code (RFC 9113 Section 7 values).
# STREAM_CLOSED (5) has "no mapping"; codes the table omits are absent too.
RST_STREAM_TO_GRPC: Final[Mapping[int, Any]] = {
    0x0: StatusCode.INTERNAL,  # NO_ERROR
    0x1: StatusCode.INTERNAL,  # PROTOCOL_ERROR
    0x2: StatusCode.INTERNAL,  # INTERNAL_ERROR
    0x3: StatusCode.INTERNAL,  # FLOW_CONTROL_ERROR
    0x4: StatusCode.INTERNAL,  # SETTINGS_TIMEOUT
    0x6: StatusCode.INTERNAL,  # FRAME_SIZE_ERROR
    0x7: StatusCode.UNAVAILABLE,  # REFUSED_STREAM: no processing occurred, safe to retry
    0x8: StatusCode.CANCELLED,  # CANCEL
    0x9: StatusCode.INTERNAL,  # COMPRESSION_ERROR
    0xA: StatusCode.INTERNAL,  # CONNECT_ERROR
    0xB: StatusCode.RESOURCE_EXHAUSTED,  # ENHANCE_YOUR_CALM
    0xC: StatusCode.PERMISSION_DENIED,  # INADEQUATE_SECURITY
}


class Retryability(enum.Enum):
    """AIP-194 guidance. gRPC itself defines no fixed retryable set (doc/statuscodes.md)."""

    AUTOMATIC = "automatic"  # retry the call, with backoff
    TRANSACTION = "transaction"  # retry the whole read-modify-write, never the single call
    GENERALLY_NOT = "generally-not"  # surface it; retry only with out-of-band knowledge
    NEVER = "never"


def retryability(code: Any) -> Retryability:
    """Classify a code under AIP-194 (unary, idempotent, non-transactional requests)."""
    if code is StatusCode.UNAVAILABLE:
        return Retryability.AUTOMATIC
    if code is StatusCode.ABORTED:
        return Retryability.TRANSACTION
    if code in {StatusCode.RESOURCE_EXHAUSTED, StatusCode.INTERNAL, StatusCode.UNKNOWN}:
        return Retryability.GENERALLY_NOT
    return Retryability.NEVER


# --- the google.rpc descriptors, built once in a private pool ---

_F = descriptor_pb2.FieldDescriptorProto
_STR, _I32, _I64, _MSG = _F.TYPE_STRING, _F.TYPE_INT32, _F.TYPE_INT64, _F.TYPE_MESSAGE


def _field(
    msg: Any, name: str, number: int, ftype: int, type_name: str = "", *, repeated: bool = False
) -> Any:
    label = _F.LABEL_REPEATED if repeated else _F.LABEL_OPTIONAL
    field = msg.field.add(name=name, number=number, type=ftype, label=label)
    if type_name:
        field.type_name = type_name
    return field


def _string_map(msg: Any, name: str, number: int, scope: str) -> None:
    entry = "".join(part.capitalize() for part in name.split("_")) + "Entry"
    nested = msg.nested_type.add(name=entry)
    nested.options.map_entry = True
    _field(nested, "key", 1, _STR)
    _field(nested, "value", 2, _STR)
    _field(msg, name, number, _MSG, f".{scope}.{entry}", repeated=True)


def _strings(msg: Any, *names: str) -> None:
    for number, name in enumerate(names, start=1):
        _field(msg, name, number, _STR)


def _build_pool() -> Any:
    pool = descriptor_pool.DescriptorPool()
    for wkt in (any_pb2, duration_pb2):
        proto = descriptor_pb2.FileDescriptorProto()
        wkt.DESCRIPTOR.CopyToProto(proto)
        pool.Add(proto)

    status = descriptor_pb2.FileDescriptorProto(
        name="google/rpc/status.proto",
        package="google.rpc",
        syntax="proto3",
        dependency=["google/protobuf/any.proto"],
    )
    msg = status.message_type.add(name="Status")
    _field(msg, "code", 1, _I32)
    _field(msg, "message", 2, _STR)
    _field(msg, "details", 3, _MSG, ".google.protobuf.Any", repeated=True)
    pool.Add(status)

    errs = descriptor_pb2.FileDescriptorProto(
        name="google/rpc/error_details.proto",
        package="google.rpc",
        syntax="proto3",
        dependency=["google/protobuf/duration.proto"],
    )
    info = errs.message_type.add(name="ErrorInfo")
    _strings(info, "reason", "domain")
    _string_map(info, "metadata", 3, "google.rpc.ErrorInfo")

    retry = errs.message_type.add(name="RetryInfo")
    _field(retry, "retry_delay", 1, _MSG, ".google.protobuf.Duration")

    debug = errs.message_type.add(name="DebugInfo")
    _field(debug, "stack_entries", 1, _STR, repeated=True)
    _field(debug, "detail", 2, _STR)

    quota = errs.message_type.add(name="QuotaFailure")
    qv = quota.nested_type.add(name="Violation")
    _strings(qv, "subject", "description", "api_service", "quota_metric", "quota_id")
    _string_map(qv, "quota_dimensions", 6, "google.rpc.QuotaFailure.Violation")
    _field(qv, "quota_value", 7, _I64)
    qv.oneof_decl.add(name="_future_quota_value")
    future = _field(qv, "future_quota_value", 8, _I64)
    future.oneof_index = 0
    future.proto3_optional = True
    _field(quota, "violations", 1, _MSG, ".google.rpc.QuotaFailure.Violation", repeated=True)

    pre = errs.message_type.add(name="PreconditionFailure")
    pv = pre.nested_type.add(name="Violation")
    _strings(pv, "type", "subject", "description")
    _field(pre, "violations", 1, _MSG, ".google.rpc.PreconditionFailure.Violation", repeated=True)

    localized = errs.message_type.add(name="LocalizedMessage")
    _strings(localized, "locale", "message")

    bad = errs.message_type.add(name="BadRequest")
    fv = bad.nested_type.add(name="FieldViolation")
    _strings(fv, "field", "description", "reason")
    _field(fv, "localized_message", 4, _MSG, ".google.rpc.LocalizedMessage")
    _field(bad, "field_violations", 1, _MSG, ".google.rpc.BadRequest.FieldViolation", repeated=True)

    request_info = errs.message_type.add(name="RequestInfo")
    _strings(request_info, "request_id", "serving_data")

    resource = errs.message_type.add(name="ResourceInfo")
    _strings(resource, "resource_type", "resource_name", "owner", "description")

    helpmsg = errs.message_type.add(name="Help")
    link = helpmsg.nested_type.add(name="Link")
    _strings(link, "description", "url")
    _field(helpmsg, "links", 1, _MSG, ".google.rpc.Help.Link", repeated=True)
    pool.Add(errs)
    return pool


POOL: Final[Any] = _build_pool()
STANDARD_DETAIL_TYPES: Final = (
    "google.rpc.ErrorInfo",
    "google.rpc.RetryInfo",
    "google.rpc.DebugInfo",
    "google.rpc.QuotaFailure",
    "google.rpc.PreconditionFailure",
    "google.rpc.BadRequest",
    "google.rpc.RequestInfo",
    "google.rpc.ResourceInfo",
    "google.rpc.Help",
    "google.rpc.LocalizedMessage",
)


def message_class(full_name: str) -> Any:
    """The generated-equivalent class for a `google.rpc.*` message in the private pool."""
    return message_factory.GetMessageClass(POOL.FindMessageTypeByName(full_name))


def make_status(code: Any, message: str, *details: Any) -> Any:
    """Build a `google.rpc.Status`, packing each detail message into a `google.protobuf.Any`."""
    status = message_class("google.rpc.Status")(code=code_number(code), message=message)
    for detail in details:
        # Deterministic serialization keeps map fields in key order, so equal inputs give equal
        # bytes (protobuf does not promise this across languages or releases).
        status.details.add().Pack(detail, deterministic=True)
    return status


# --- the grpc-status-details-bin contract (same shape as grpc_status.rpc_status) ---


class _Status(NamedTuple):
    """A `grpc.Status`: what `abort_with_status` accepts."""

    code: Any
    details: str
    trailing_metadata: tuple[tuple[str, bytes], ...]


class StatusMismatchError(ValueError):
    """`grpc-status-details-bin` contradicts the outer `grpc-status` or `grpc-message`."""


class MalformedDetailsError(ValueError):
    """`grpc-status-details-bin` is not a parseable `google.rpc.Status`."""


def to_grpc_status(status: Any) -> Any:
    """Convert a `google.rpc.Status` to a `grpc.Status` for `abort_with_status`.

    Mirrors `grpc_status.rpc_status.to_status`, except that it also refuses `OK`: the
    grpc.aio `abort` path asserts a non-OK code and then leaves the RPC unanswered.
    """
    if status.code == 0:
        raise ValueError("an error Status must not carry code 0 (OK)")
    if status.code not in _BY_NUMBER:
        raise ValueError(f"Invalid status code {status.code}")
    return _Status(
        code=_BY_NUMBER[status.code],
        details=status.message,
        trailing_metadata=((DETAILS_KEY, status.SerializeToString(deterministic=True)),),
    )


def from_trailing_metadata(
    code: Any, details: str | None, trailing_metadata: Iterable[tuple[str, str | bytes]] | None
) -> Any | None:
    """Recover the rich `google.rpc.Status` from a finished call, or None if there is none.

    Mirrors `grpc_status.rpc_status.from_call`: the first `grpc-status-details-bin` entry wins,
    and its `code` and `message` must equal the call's, because PROTOCOL-HTTP2 says the consumer
    "MUST verify" that the details do not contradict `grpc-status`.
    """
    if trailing_metadata is None:
        return None
    for key, value in trailing_metadata:
        if key != DETAILS_KEY:
            continue
        if isinstance(value, str):
            raise MalformedDetailsError(f"{DETAILS_KEY} arrived as text, not bytes")
        rich = message_class("google.rpc.Status")()
        try:
            rich.ParseFromString(value)
        except DecodeError as exc:
            raise MalformedDetailsError(str(exc)) from exc
        if code_number(code) != rich.code:
            raise StatusMismatchError(
                f"Code in Status proto ({rich.code}) doesn't match status code ({code})"
            )
        if (details or "") != rich.message:
            raise StatusMismatchError(
                f"Message in Status proto ({rich.message!r}) doesn't match ({details!r})"
            )
        return rich
    return None


@dataclass(frozen=True, slots=True)
class UnknownDetail:
    """An `Any` whose type this process cannot resolve; kept verbatim, never dropped."""

    type_url: str
    value: bytes


def unpack_details(status: Any, *, pool: Any = POOL) -> tuple[Any, ...]:
    """Resolve every `Status.details` entry to a typed message, or an `UnknownDetail`.

    `Any.TypeName()` keeps only the text after the last `/` of `type_url`, so the URL prefix
    (`type.googleapis.com/` by convention) never selects the type; a URL with no `/` is not
    resolvable at all (`Any.Is` requires one).
    """
    out: list[Any] = []
    for packed in status.details:
        try:
            descriptor = pool.FindMessageTypeByName(packed.TypeName())
        except KeyError:
            out.append(UnknownDetail(packed.type_url, packed.value))
            continue
        inner = message_factory.GetMessageClass(descriptor)()
        if packed.Unpack(inner):
            out.append(inner)
        else:
            out.append(UnknownDetail(packed.type_url, packed.value))
    return tuple(out)


def find_detail(details: Iterable[Any], full_name: str) -> Any | None:
    """The first resolved detail of one type, or None (AIP-193 allows each type at most once)."""
    for detail in details:
        if not isinstance(detail, UnknownDetail) and detail.DESCRIPTOR.full_name == full_name:
            return detail
    return None


def details_trailer_cost(status: Any) -> int:
    """Return the decoded details field size reported by gRPC Core 1.85.1.

    The per-field diagnostic adds the name length, decoded value length, and 32 bytes.
    The HPACK parser applies limits to a different total, which includes the true-binary
    marker or the base64 representation and the other fields in the block.
    """
    return _NAME_BYTES + len(status.SerializeToString(deterministic=True)) + _PER_FIELD_OVERHEAD


# --- what a client does with a failed call ---


@dataclass(frozen=True, slots=True)
class ErrorReport:
    """A failed call reduced to the facts a client branches on."""

    code: Any
    message: str
    rich: bool
    retryability: Retryability
    reason: str | None = None
    domain: str | None = None
    retry_after_seconds: float | None = None
    field_violations: tuple[tuple[str, str], ...] = ()
    unknown_types: tuple[str, ...] = ()


def describe(
    code: Any, details: str | None, trailing_metadata: Iterable[tuple[str, str | bytes]] | None
) -> ErrorReport:
    """Reduce a finished call to an `ErrorReport`, unpacking `google.rpc.Status` if present."""
    rich = from_trailing_metadata(code, details, trailing_metadata)
    if rich is None:
        return ErrorReport(code, details or "", rich=False, retryability=retryability(code))
    unpacked = unpack_details(rich)
    info = find_detail(unpacked, "google.rpc.ErrorInfo")
    retry = find_detail(unpacked, "google.rpc.RetryInfo")
    bad = find_detail(unpacked, "google.rpc.BadRequest")
    return ErrorReport(
        code,
        rich.message,
        rich=True,
        retryability=retryability(code),
        reason=info.reason if info is not None else None,
        domain=info.domain if info is not None else None,
        retry_after_seconds=(
            retry.retry_delay.ToTimedelta().total_seconds() if retry is not None else None
        ),
        field_violations=(
            tuple((v.field, v.description) for v in bad.field_violations) if bad is not None else ()
        ),
        unknown_types=tuple(d.type_url for d in unpacked if isinstance(d, UnknownDetail)),
    )
