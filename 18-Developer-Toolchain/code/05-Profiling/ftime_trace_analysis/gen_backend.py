"""Write backend_heavy.cpp: no includes and no templates, but many loops for the optimizer.

The file costs almost nothing to parse and a lot to optimize at -O2, so its trace is
dominated by the Backend and Optimizer events instead of Frontend.
"""

import sys

FUNCTIONS = 400


def main() -> None:
    out = sys.argv[1]
    lines = ["// Generated by gen_backend.py; do not edit."]
    for i in range(FUNCTIONS):
        lines.append(
            f"double kernel_{i}(const double* a, const double* b, int n) {{\n"
            f"    double s = 0.0;\n"
            f"    for (int k = 0; k < n; ++k) {{\n"
            f"        s += a[k] * b[k] * {i + 1}.5 + a[(k * 7 + {i}) % n] - b[k] / (a[k] + {i + 2}.0);\n"
            f"        if (s > {1000 + i}.0) s *= 0.5;\n"
            f"    }}\n"
            f"    for (int k = 0; k + 1 < n; ++k) s += a[k + 1] * b[k];\n"
            f"    return s;\n"
            f"}}"
        )
    with open(out, "w", encoding="ascii") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
