#!/usr/bin/env python3
"""schemagen (as shipped, broken): compile a .schema file into a C header plus a depfile.

Usage: schemagen.py --root ROOT IN.schema OUT.h OUT.h.d

Schema language, one directive per line:
    # comment                  ignored, never reaches the header
    import <path>              path relative to ROOT; the rest of the line, spaces allowed
    const <NAME> <VALUE>       becomes #define NAME VALUE
    struct <Name>              starts a struct
    field <name> <ctype>       adds a member to the current struct

This file is the drill's starting point. It produces a correct header, but its build
metadata is wrong in five ways; the drill asks you to find them from the build's behavior.
Fault-injection knobs, identical in both generators so the lab can compare them:
    SCHEMAGEN_DELAY=SECONDS    sleep after parsing, before writing (a slow generator)
    SCHEMAGEN_CRASH_MIDWRITE=1 die after writing half of the header bytes
"""

from __future__ import annotations

import os
import sys
import time


def parse(root: str, path: str, consts: dict, structs: list, direct_imports: list, depth: int) -> None:
    with open(os.path.join(root, path), encoding="ascii") as f:
        for raw in f:
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            word, _, rest = line.partition(" ")
            if word == "import":
                if depth == 0:
                    direct_imports.append(rest)
                parse(root, rest, consts, structs, direct_imports, depth + 1)
            elif word == "const":
                name, value = rest.split()
                consts[name] = value
            elif word == "struct":
                structs.append((rest, []))
            elif word == "field":
                name, ctype = rest.split()
                structs[-1][1].append((name, ctype))
            else:
                raise SystemExit(f"{path}: unknown directive {word!r}")


def render(src: str, out: str, consts: dict, structs: list) -> str:
    guard = "GEN_" + os.path.basename(out).replace(".", "_").upper()
    lines = [f"/* generated by schemagen from {src}; do not edit */", f"#ifndef {guard}", f"#define {guard}"]
    lines.append("#include <stdint.h>")
    for name, value in consts.items():
        lines.append(f"#define {name} {value}")
    for name, fields in structs:
        members = " ".join(f"{ctype} {fname};" for fname, ctype in fields)
        lines.append(f"struct {name} {{ {members} }};")
    lines.append(f"#endif /* {guard} */")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    if len(argv) != 6 or argv[1] != "--root":
        raise SystemExit(__doc__)
    root, src, out, depfile = argv[2], argv[3], argv[4], argv[5]
    consts: dict = {}
    structs: list = []
    direct_imports: list = []
    parse(root, src, consts, structs, direct_imports, 0)
    text = render(src, out, consts, structs)
    time.sleep(float(os.environ.get("SCHEMAGEN_DELAY", "0")))

    # Write the header in place, every time.
    with open(out, "w", encoding="ascii") as f:
        if os.environ.get("SCHEMAGEN_CRASH_MIDWRITE") == "1":
            f.write(text[: len(text) // 2])
            f.flush()
            os._exit(1)
        f.write(text)

    # Depfile: "the header depends on the schema and what it imports".
    deps = [os.path.join(root, src)] + [os.path.join(root, p) for p in direct_imports]
    with open(depfile, "w", encoding="ascii") as f:
        f.write(os.path.basename(out) + ": " + " ".join(deps) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
