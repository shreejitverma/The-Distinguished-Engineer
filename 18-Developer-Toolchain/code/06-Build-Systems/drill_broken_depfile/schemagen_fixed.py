#!/usr/bin/env python3
"""schemagen (model solution): compile a .schema file into a C header plus a correct depfile.

Usage: schemagen.py --root ROOT IN.schema OUT.h OUT.h.d

Same schema language and the same fault-injection knobs as schemagen_broken.py.
The five fixes, each tied to a bug the drill exposes:
  1. The depfile lists every file the generator opened, transitively, not just direct imports.
  2. The depfile target is exactly the output path the build manifest declared (OUT as given).
  3. Paths are escaped for the Makefile subset Ninja and CMake parse: space, '#', and '$'.
  4. The header is rewritten only when its bytes change, so `restat = 1` can prune consumers.
  5. Header and depfile are written to a temporary file in the same directory and renamed,
     so no reader, and no crash, can ever see a half-written header.
"""

from __future__ import annotations

import os
import sys
import tempfile
import time


def parse(root: str, path: str, consts: dict, structs: list, opened: list, stack: tuple) -> None:
    if path in stack:
        raise SystemExit(f"import cycle: {' -> '.join(stack + (path,))}")
    if path not in opened:
        opened.append(path)  # record before reading: a failed read still names its input
    with open(os.path.join(root, path), encoding="ascii") as f:
        for raw in f:
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            word, _, rest = line.partition(" ")
            if word == "import":
                parse(root, rest, consts, structs, opened, stack + (path,))
            elif word == "const":
                name, value = rest.split()
                consts[name] = value
            elif word == "struct":
                structs.append((rest, []))
            elif word == "field":
                name, ctype = rest.split()
                structs[-1][1].append((name, ctype))
            else:
                raise SystemExit(f"{path}: unknown directive {word!r}")


def render(src: str, out: str, consts: dict, structs: list) -> str:
    guard = "GEN_" + os.path.basename(out).replace(".", "_").upper()
    lines = [f"/* generated by schemagen from {src}; do not edit */", f"#ifndef {guard}", f"#define {guard}"]
    lines.append("#include <stdint.h>")
    for name, value in consts.items():
        lines.append(f"#define {name} {value}")
    for name, fields in structs:
        members = " ".join(f"{ctype} {fname};" for fname, ctype in fields)
        lines.append(f"struct {name} {{ {members} }};")
    lines.append(f"#endif /* {guard} */")
    return "\n".join(lines) + "\n"


def depfile_path(root: str, path: str) -> str:
    """Spell a dependency the way the build manifest spells it: relative to the build's cwd
    when it lies under it, absolute otherwise (Ninja compares path strings, not inodes)."""
    full = os.path.abspath(os.path.join(root, path))
    rel = os.path.relpath(full)
    return full if rel.startswith("..") else rel


def escape(path: str) -> str:
    if "\n" in path or "\r" in path:
        raise SystemExit(f"cannot express a newline in a depfile path: {path!r}")
    # Order matters only for '$'; backslashes not before a space or '#' are literal in Ninja's parser.
    return path.replace("$", "$$").replace("#", "\\#").replace(" ", "\\ ")


def write_atomically(path: str, text: str, crash_midway: bool = False) -> None:
    directory = os.path.dirname(path) or "."
    fd, tmp = tempfile.mkstemp(prefix=".schemagen-", dir=directory)
    try:
        with os.fdopen(fd, "w", encoding="ascii") as f:
            if crash_midway:
                f.write(text[: len(text) // 2])
                f.flush()
                os._exit(1)  # the temporary file is left behind, the real output is untouched
            f.write(text)
        os.replace(tmp, path)  # rename(2): readers see the old file or the new one, never a mix
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def main(argv: list[str]) -> int:
    if len(argv) != 6 or argv[1] != "--root":
        raise SystemExit(__doc__)
    root, src, out, depfile = argv[2], argv[3], argv[4], argv[5]
    consts: dict = {}
    structs: list = []
    opened: list = []
    parse(root, src, consts, structs, opened, ())
    text = render(src, out, consts, structs)
    time.sleep(float(os.environ.get("SCHEMAGEN_DELAY", "0")))

    try:
        with open(out, encoding="ascii") as f:
            unchanged = f.read() == text
    except FileNotFoundError:
        unchanged = False
    if not unchanged:
        write_atomically(out, text, os.environ.get("SCHEMAGEN_CRASH_MIDWRITE") == "1")

    deps = " ".join(escape(depfile_path(root, p)) for p in opened)
    write_atomically(depfile, f"{escape(out)}: {deps}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
