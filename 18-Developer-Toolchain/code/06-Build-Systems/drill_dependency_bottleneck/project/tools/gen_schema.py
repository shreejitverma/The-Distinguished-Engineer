"""Toy schema compiler: one field name per line in, a C++ struct out.

It sleeps DRILL_CODEGEN_SECONDS (default 3) first, to stand in for a code generator
that is slow on a large input (protoc, flatc, or LLVM tablegen on a big .td tree).
The header is written to a temporary name and renamed, so a compile that races the
generator sees either no header or a complete one, never half of one.
"""

from __future__ import annotations

import os
import sys
import time
from pathlib import Path


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: gen_schema.py SCHEMA.def OUT.h", file=sys.stderr)
        return 2
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    fields = [line.strip() for line in src.read_text().splitlines() if line.strip()]
    if not fields:
        print(f"gen_schema.py: no fields in {src}", file=sys.stderr)
        return 1
    time.sleep(float(os.environ.get("DRILL_CODEGEN_SECONDS", "3")))
    body = "".join(f"  long long {name};\n" for name in fields)
    text = (
        "// Generated by gen_schema.py; do not edit.\n"
        "#pragma once\n"
        "namespace core {\n"
        "struct Order {\n" + body + "};\n"
        f"inline constexpr int kOrderFieldCount = {len(fields)};\n"
        "}  // namespace core\n"
    )
    out.parent.mkdir(parents=True, exist_ok=True)
    tmp = out.with_suffix(".h.tmp")
    tmp.write_text(text)
    os.replace(tmp, out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
