#!/usr/bin/env python3
"""AST codemod campaign over a synthetic fleet of six git repositories.

The migration: old_api.fetch(url, timeout_ms) becomes new_api.get(url, timeout_s=...).
The unit changes from milliseconds to seconds, so a rename alone is wrong.

Stages, each with a check that fails loudly if the mechanism is absent:
  1. A text (regex) codemod versus an AST-anchored codemod that edits byte spans.
  2. Sharding by repository and CODEOWNERS owner, with a cap on files per shard.
  3. Rollout in waves (canary first); each shard is tested on its own branch and
     either fast-forward merged or quarantined, and pre-existing failures are ignored.
  4. A burndown census, idempotence of a re-run, and a ratchet that catches backsliding.
  5. A second fleet where the canary fails, to show that the campaign halts.
"""
