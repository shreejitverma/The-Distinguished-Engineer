# ---------------------------------------------------------------- git and tests


def git(repo, *args):
    p = subprocess.run(
        ["git", "-C", str(repo), "-c", "commit.gpgsign=false", *args],
        capture_output=True,
        text=True,
    )
    if p.returncode != 0:
        die("git %s failed: %s" % (" ".join(args), p.stderr.strip()))
    return p.stdout


def build_fleet(root):
    root.mkdir()
    libs = root / "_libs"
    libs.mkdir()
    for name, text in LIBS.items():
        (libs / name).write_text(text, encoding="utf-8")
    for repo, files in FLEET.items():
        rd = root / repo
        for rel, text in files.items():
            path = rd / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(text.encode("utf-8"))
        git(rd, "init", "-q", "-b", "main")
        git(rd, "add", "-A")
        git(rd, "commit", "-q", "-m", "base")
    return root


def run_tests(repo, libs):
    env = dict(os.environ, PYTHONPATH=str(libs), PYTHONDONTWRITEBYTECODE="1")
    code = (
        "import os,unittest;"
        "r=unittest.TextTestRunner(stream=open(os.devnull,'w')).run("
        "unittest.defaultTestLoader.discover('.',pattern='test_*.py'));"
        "print(r.testsRun,len(r.failures)+len(r.errors))"
    )
    p = subprocess.run([sys.executable, "-c", code], cwd=repo, env=env, capture_output=True, text=True)
    last = p.stdout.strip().splitlines()[-1:] or [""]
    parts = last[0].split()
    check(p.returncode == 0 and len(parts) == 2, "test runner broke in %s: %s" % (repo.name, p.stderr[-300:]))
    return int(parts[0]), int(parts[1])


# ---------------------------------------------------------------- the codemod


def local_names(fn):
    """Names bound inside one function body: parameters plus every Store target."""
    names = set()
    a = fn.args
    for arg in a.posonlyargs + a.args + a.kwonlyargs:
        names.add(arg.arg)
    if a.vararg:
        names.add(a.vararg.arg)
    if a.kwarg:
        names.add(a.kwarg.arg)
    if isinstance(fn, ast.Lambda):
        return names
    stack = list(fn.body)
    while stack:
        n = stack.pop()
        if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            names.add(n.name)
            continue
        if isinstance(n, ast.Lambda):
            continue
        if isinstance(n, ast.Name) and isinstance(n.ctx, ast.Store):
            names.add(n.id)
        stack.extend(ast.iter_child_nodes(n))
    return names


class Finder(ast.NodeVisitor):
    def __init__(self, mod_names, fn_names):
        self.mod_names, self.fn_names = mod_names, fn_names
        self.scopes = []
        self.refs = []
        self.calls = []
        self.dynamic = 0

    def shadowed(self, name):
        return any(name in s for s in self.scopes)

    def bound(self, name):
        return (name in self.mod_names or name in self.fn_names) and not self.shadowed(name)

    def visit_FunctionDef(self, node):
        outer = list(node.decorator_list) + list(node.args.defaults)
        outer += [d for d in node.args.kw_defaults if d is not None]
        for n in outer:
            self.visit(n)
        self.scopes.append(local_names(node))
        for st in node.body:
            self.visit(st)
        self.scopes.pop()

    visit_AsyncFunctionDef = visit_FunctionDef

    def visit_Lambda(self, node):
        for n in list(node.args.defaults) + [d for d in node.args.kw_defaults if d is not None]:
            self.visit(n)
        self.scopes.append(local_names(node))
        self.visit(node.body)
        self.scopes.pop()

    def visit_Name(self, node):
        if isinstance(node.ctx, ast.Load) and self.bound(node.id):
            self.refs.append(node)

    def visit_Call(self, node):
        f = node.func
        if (
            isinstance(f, ast.Attribute)
            and f.attr == OLD_FN
            and isinstance(f.value, ast.Name)
            and f.value.id in self.mod_names
            and not self.shadowed(f.value.id)
        ):
            self.calls.append((node, "attr"))
        elif isinstance(f, ast.Name) and f.id in self.fn_names and not self.shadowed(f.id):
            self.calls.append((node, "name"))
        elif (
            isinstance(f, ast.Name)
            and f.id == "getattr"
            and len(node.args) >= 2
            and isinstance(node.args[0], ast.Name)
            and self.bound(node.args[0].id)
            and node.args[0].id in self.mod_names
            and isinstance(node.args[1], ast.Constant)
            and node.args[1].value == OLD_FN
        ):
            self.dynamic += 1
        self.generic_visit(node)


def line_starts(src):
    starts, pos = [0], 0
    for line in src.split(b"\n")[:-1]:
        pos += len(line) + 1
        starts.append(pos)
    return starts


def span(starts, node):
    """Byte span of a node: col_offset is a UTF-8 byte offset, not a character offset."""
    return (
        starts[node.lineno - 1] + node.col_offset,
        starts[node.end_lineno - 1] + node.end_col_offset,
    )


def timeout_arg(call):
    """Return the node that carries the old timeout, or None if the call is not analyzable."""
    if any(isinstance(a, ast.Starred) for a in call.args):
        return None
    if any(k.arg is None for k in call.keywords):
        return None
    kw = {k.arg: k for k in call.keywords}
    if len(kw) != len(call.keywords):  # ast.parse accepts a repeated keyword; compile() does not
        return None
    if len(call.args) > 2 or not set(kw) <= {"url", "timeout"}:
        return None
    if call.args and "url" in kw:
        return None
    if len(call.args) == 2:
        return None if "timeout" in kw else call.args[1]
    return kw.get("timeout")


def seconds_text(src, starts, node):
    if isinstance(node, ast.Constant) and type(node.value) is int and node.value >= 0:
        return format(Decimal(node.value).scaleb(-3).normalize(), "f")
    s, e = span(starts, node)
    txt = src[s:e].decode("utf-8")
    atomic = isinstance(node, (ast.Name, ast.Attribute, ast.Call, ast.Subscript, ast.Constant))
    return ("%s / 1000" if atomic else "(%s) / 1000") % txt


def analyze(src):
    res = {
        "status": "ok",
        "static": 0,
        "unmigratable": 0,
        "dynamic": 0,
        "func_lines": set(),
        "static_lines": set(),
        "new": None,
    }
    if any(m in b"\n".join(src.split(b"\n")[:5]) for m in GENERATED_MARKERS):
        res["status"] = "generated"
        return res
    try:
        tree = ast.parse(src)
    except SyntaxError:
        res["status"] = "parse-error"
        return res
    mod_names, fn_names, new_imported = {}, {}, False
    for st in tree.body:
        if isinstance(st, ast.Import):
            for al in st.names:
                if al.name == OLD_MOD:
                    if len(st.names) != 1:
                        res["status"] = "manual-import"
                        return res
                    mod_names[al.asname or al.name] = (st, al.asname)
                if al.name == NEW_MOD and al.asname is None:
                    new_imported = True
        elif isinstance(st, ast.ImportFrom) and st.module == OLD_MOD and st.level == 0:
            for al in st.names:
                if al.name == OLD_FN:
                    if len(st.names) != 1:
                        res["status"] = "manual-import"
                        return res
                    fn_names[al.asname or al.name] = (st, al.asname)
    if not mod_names and not fn_names:
        return res
    fd = Finder(mod_names, fn_names)
    fd.visit(tree)
    res["dynamic"] = fd.dynamic
    starts = line_starts(src)

    plans = []  # (call, kind, timeout node, binding name)
    for call, kind in fd.calls:
        res["func_lines"].add(call.func.lineno)
        name = call.func.value.id if kind == "attr" else call.func.id
        t = timeout_arg(call)
        ok = t is not None
        if ok and kind == "attr":
            e = span(starts, call.func)[1]
            ok = src[e - len(OLD_FN) : e] == OLD_FN.encode()
        plans.append((call, kind, t, name, ok))

    # An aliased module import that is still used elsewhere cannot be replaced safely.
    consumed = {id(c.func.value if k == "attr" else c.func) for c, k, _, _, ok in plans if ok}
    other_refs = {}
    for r in fd.refs:
        if id(r) not in consumed:
            other_refs[r.id] = other_refs.get(r.id, 0) + 1
    final = []
    for call, kind, t, name, ok in plans:
        if ok and kind == "attr" and mod_names[name][1] and other_refs.get(name):
            ok = False
        final.append((call, kind, t, name, ok))
    res["static_lines"] = {call.func.lineno for call, _, _, _, ok in final if ok}
    res["static"] = sum(1 for p in final if p[4])
    res["unmigratable"] = len(final) - res["static"]
    if res["static"] == 0:
        return res

    edits = []  # (start, end, bytes)
    used = set()
    unaliased_needed = False
    for call, kind, t, name, ok in final:
        if not ok:
            continue
        used.add(name)
        f = call.func
        if kind == "name":
            s, e = span(starts, f)
            edits.append((s, e, ("%s.%s" % (NEW_MOD, NEW_FN)).encode()))
            unaliased_needed = True
        else:
            e = span(starts, f)[1]
            edits.append((e - len(OLD_FN), e, NEW_FN.encode()))
            if mod_names[name][1] is None:
                s, e2 = span(starts, f.value)
                edits.append((s, e2, NEW_MOD.encode()))
                unaliased_needed = True
        value = t.value if isinstance(t, ast.keyword) else t
        ts, te = span(starts, t)  # the keyword node, or the positional expression
        edits.append((ts, te, ("timeout_s=" + seconds_text(src, starts, value)).encode()))

    provided = new_imported
    pending_insert = None
    for name in sorted(used):
        st, alias = (mod_names.get(name) or fn_names.get(name))
        s, e = span(starts, st)
        if not other_refs.get(name):
            text = "import %s" % NEW_MOD + (" as %s" % alias if alias and name in mod_names else "")
            edits.append((s, e, text.encode()))
            if not (alias and name in mod_names):
                provided = True
        elif pending_insert is None:
            pending_insert = e
    if unaliased_needed and not provided:
        e = pending_insert
        if e is None:
            first = min(span(starts, (mod_names.get(n) or fn_names.get(n))[0])[1] for n in used)
            e = first
        nl = src.find(b"\n", e)
        if nl == -1:
            edits.append((len(src), len(src), ("\nimport %s\n" % NEW_MOD).encode()))
        else:
            edits.append((nl + 1, nl + 1, ("import %s\n" % NEW_MOD).encode()))

    edits.sort()
    for (s1, e1, _), (s2, e2, _) in zip(edits, edits[1:]):
        check(e1 <= s2, "overlapping edits in codemod output")
    out = src
    for s, e, text in reversed(edits):
        out = out[:s] + text + out[e:]
    try:
        ast.parse(out)
    except SyntaxError:
        die("codemod produced a file that does not parse")
    res["new"] = out
    return res


# ---------------------------------------------------------------- ownership and shards


def load_rules(repo):
    rules = []
    cf = repo / "CODEOWNERS"
    if cf.exists():
        for line in cf.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#"):
                pat, owner = line.split()[:2]
                rules.append((pat, owner))
    return rules


def pattern_matches(pat, rel):
    """A subset of CODEOWNERS syntax: *, /dir/, /path, and *.ext."""
    if pat == "*":
        return True
    if pat.startswith("/"):
        p = pat[1:]
        if p.endswith("/"):
            return rel.startswith(p)
        return rel == p or fnmatch.fnmatchcase(rel, p)
    return fnmatch.fnmatchcase(os.path.basename(rel), pat)


def owner_of(rel, rules):
    owner = "@unowned"
    for pat, own in rules:  # last matching rule wins
        if pattern_matches(pat, rel):
            owner = own
    return owner


def repo_files(repo):
    for p in sorted(repo.rglob("*")):
        rel = p.relative_to(repo).as_posix()
        if p.is_file() and not rel.startswith(".git/") and not os.path.basename(rel).startswith("test_"):
            yield rel, p


def plan_repo(repo):
    rules = load_rules(repo)
    by_owner = {}
    for rel, p in repo_files(repo):
        if not rel.endswith(".py"):
            continue
        res = analyze(p.read_bytes())
        if res["new"] is not None:
            by_owner.setdefault(owner_of(rel, rules), []).append((rel, res))
    shards = []
    for owner in sorted(by_owner):
        files = by_owner[owner]
        for i in range(0, len(files), MAX_FILES_PER_SHARD):
            chunk = files[i : i + MAX_FILES_PER_SHARD]
            shards.append(
                {
                    "id": "%s/%s#%d" % (repo.name, owner, i // MAX_FILES_PER_SHARD + 1),
                    "repo": repo,
                    "owner": owner,
                    "files": chunk,
                    "calls": sum(r["static"] for _, r in chunk),
                }
            )
    return shards


def plan_fleet(fleet):
    shards = []
    for repo in sorted(p for p in fleet.iterdir() if p.is_dir() and not p.name.startswith("_")):
        shards.extend(plan_repo(repo))
    return shards


# ---------------------------------------------------------------- shard pipeline


def process_shard(shard, libs):
    repo = shard["repo"]
    branch = "lsc-%s-%s" % (repo.name, shard["owner"].lstrip("@").replace("/", "-"))
    branch += "-%s" % shard["id"].rsplit("#", 1)[1]
    _, before = run_tests(repo, libs)
    git(repo, "checkout", "-q", "-b", branch)
    for rel, res in shard["files"]:
        (repo / rel).write_bytes(res["new"])
    _, after = run_tests(repo, libs)
    if after <= before:
        git(repo, "add", "-A")
        git(repo, "commit", "-q", "-m", "LSC: migrate old_api.fetch (%s)" % shard["id"])
        git(repo, "checkout", "-q", "main")
        git(repo, "merge", "-q", "--ff-only", branch)
        verdict = "MERGED"
    else:
        git(repo, "checkout", "-q", "-f", "main")
        verdict = "QUARANTINED"
    git(repo, "branch", "-q", "-D", branch)
    return verdict, before, after


def run_campaign(fleet, libs, order_override=None):
    shards = plan_fleet(fleet)
    shards.sort(key=lambda s: (s["calls"], s["id"]))
    if order_override:
        shards.sort(key=lambda s: (0 if s["id"] in order_override else 1, s["calls"], s["id"]))
    log, halted, i = [], False, 0
    for w, size in enumerate(WAVES):
        wave = shards[i:] if size is None else shards[i : i + size]
        i += len(wave)
        failed = 0
        for s in wave:
            verdict, before, after = process_shard(s, libs)
            failed += verdict != "MERGED"
            log.append((w, s, verdict, before, after))
            print(
                "  wave %d  %-26s files=%d calls=%d  failing %d -> %d  %s"
                % (w, s["id"], len(s["files"]), s["calls"], before, after, verdict)
            )
        if w == 0 and failed:
            halted = True
        elif wave and failed / len(wave) > HALT_FRACTION:
            halted = True
        if halted:
            print("  HALT after wave %d: %d shard(s) not started" % (w, len(shards) - i))
            break
    return log, halted, shards[i:] if halted else []


