def census(fleet):
    c = {"static": 0, "unmigratable": 0, "dynamic": 0, "generated": 0, "parse-error": 0, "text_lines": 0}
    per_file = {}
    for repo in sorted(p for p in fleet.iterdir() if p.is_dir() and not p.name.startswith("_")):
        for rel, p in repo_files(repo):
            raw = p.read_bytes()
            res = analyze(raw) if rel.endswith(".py") else {"status": "ok", "static": 0, "unmigratable": 0, "dynamic": 0, "func_lines": set()}
            if res["status"] in ("generated", "parse-error"):
                c[res["status"]] += 1
                continue
            c["static"] += res["static"]
            c["unmigratable"] += res["unmigratable"]
            c["dynamic"] += res["dynamic"]
            if res["static"] + res["unmigratable"]:
                per_file["%s/%s" % (repo.name, rel)] = res["static"] + res["unmigratable"]
            for n, line in enumerate(raw.decode("utf-8").splitlines(), 1):
                if (OLD_MOD + "." + OLD_FN) in line and n not in res["func_lines"]:
                    c["text_lines"] += 1
    return c, per_file


def regex_hits(fleet):
    hits = set()
    pat = re.compile(r"\bold_api\.fetch\(")
    for repo in sorted(p for p in fleet.iterdir() if p.is_dir() and not p.name.startswith("_")):
        for rel, p in repo_files(repo):
            for n, line in enumerate(p.read_text(encoding="utf-8").splitlines(), 1):
                if pat.search(line):
                    hits.add(("%s/%s" % (repo.name, rel), n))
    return hits


def migratable_sites(fleet):
    """Lines analyze() would edit. Compared with HAND_SITES, which it must not define."""
    sites = set()
    for repo in sorted(p for p in fleet.iterdir() if p.is_dir() and not p.name.startswith("_")):
        for rel, p in repo_files(repo):
            if rel.endswith(".py"):
                res = analyze(p.read_bytes())
                if res["status"] == "ok":
                    for ln in res["static_lines"]:
                        sites.add(("%s/%s" % (repo.name, rel), ln))
    return sites


