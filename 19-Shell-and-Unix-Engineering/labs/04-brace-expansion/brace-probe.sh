#!/bin/sh
# brace-probe.sh: show what the shell under test does with brace expansion, one behavior per mode.
# Usage: brace-probe.sh MODE [DIR]
# Each mode prints what the shell produced, with every word between angle brackets.
# Code that is a syntax error in some shell sits in a single-quoted eval string, so the
# rest of the file still parses there and shfmt leaves the layout of that code alone.
# shellcheck disable=SC3009 # brace expansion is the behavior under test in every mode

# args ARG...: print the argument count, then each argument between angle brackets.
args() {
  printf '%d args:' "$#"
  if [ "$#" -gt 0 ]; then
    printf ' <%s>' "$@"
  fi
  printf '\n'
}

mode=${1-}

case $mode in
  list)
    # Comma lists: prefix and suffix, cross product, nesting, source order, names that do not exist.
    args a{b,c}d
    args {a,b}{1,2}
    args a{b,{c,d}}e
    args {c,a,b}
    args /nonexistent-brace-lab/{x,y}
    ;;

  range)
    # Sequence expressions: ascending, descending, letters, negative endpoints.
    args {1..5}
    args {5..1}
    args {a..e}
    args {-2..2}
    ;;

  step)
    # The third term: a step that agrees with the direction, one that does not, and a negative one.
    args {1..10..3}
    args {10..1..3}
    args {1..10..-3}
    ;;

  pad)
    # Leading zeros: padding in some shells, an octal number in others.
    args {08..10}
    args {010..012}
    args {-01..1}
    ;;

  width)
    # Two endpoints just below 2^63: a shell that keeps them in a 32-bit int prints -2 and -1.
    args {9223372036854775806..9223372036854775807}
    ;;

  order)
    # Does brace expansion run before or after parameter and tilde expansion?
    n=3
    # shellcheck disable=SC2051,SC2248 # a variable as a range endpoint is the behavior under test
    args {1..$n}
    x=a
    x1=one
    x2=two
    # shellcheck disable=SC2086,SC2248,SC2154 # unquoted on purpose; bash reads this as $x1 $x2
    args $x{1,2}
    # shellcheck disable=SC2086,SC2248 # unquoted on purpose
    args ${x}{1,2}
    # shellcheck disable=SC2088 # a tilde generated by a brace list is the behavior under test
    args {~,x}
    : "$x1" "$x2"
    ;;

  from-expansion)
    # Braces that arrive in the result of an expansion instead of in the script text.
    x='{a,b}'
    # shellcheck disable=SC2086,SC2248 # unquoted on purpose: is the value brace expanded?
    args $x
    args "$x"
    y=a,b
    # shellcheck disable=SC2086,SC2248,SC1083 # unquoted on purpose: is the comma in the value a separator?
    args {$y}
    # shellcheck disable=SC2046 # unquoted on purpose: is command output brace expanded?
    args $(printf '%s\n' '{c,d}')
    ;;

  quoting)
    # Quoting a brace or a comma removes its special meaning; quoting other text does not.
    args "{a,b}"
    args '{a,b}'
    # shellcheck disable=SC1083 # a brace word with only a quoted comma is the behavior under test
    args {a\,b}
    args {a,"b,c"}
    args {a,b\ c}
    args a{b,c}"{d,e}"
    ;;

  malformed)
    # Words that look like brace expansions and are not, and empty alternatives.
    # shellcheck disable=SC1083 # a brace word with no comma is the behavior under test
    args {a}
    args {}
    # shellcheck disable=SC1083 # a lone opening brace is the behavior under test
    args {a,b
    args x{,}y
    args {a,}
    args {,}
    args {a,b}{}
    ;;

  failed-sequence)
    # A sequence that is not valid, next to a list that is.
    args {1..x}{a,b}
    args {{1,2}..3}
    ;;

  assign)
    # Assignment words are not brace expanded; arguments of export are ordinary words in bash.
    # shellcheck disable=SC2125 # the literal value is the behavior under test
    x={a,b}
    args "$x"
    # shellcheck disable=SC2125,SC2163 # bash reads this as export y=a y=b
    export y={a,b}
    args "$y"
    ;;

  dollar-at)
    # A brace list next to "$@": bash copies the text "$@" into every generated word.
    set -- 1 2
    # shellcheck disable=SC2145 # "$@" glued to a brace list is the behavior under test
    args "$@"{a,b}
    ;;

  case-pattern)
    # A case pattern is not brace expanded, so {a,b} matches only the five-character string.
    # shellcheck disable=SC2194 # a constant subject is the point: only the pattern varies
    case a in
      {a,b}) echo "a: matched" ;;
      *) echo "a: no match" ;;
    esac
    # shellcheck disable=SC2194 # a constant subject is the point: only the pattern varies
    case '{a,b}' in
      {a,b}) echo "{a,b}: matched" ;;
      *) echo "{a,b}: no match" ;;
    esac
    ;;

  redirect)
    # A brace list as a redirection target, in the directory DIR.
    cd "$2" || exit 1
    # shellcheck disable=SC2261,SC2094 # more than one target is the behavior under test
    { true >{a,b}; } 2>/dev/null
    rc=$?
    echo "status=$rc"
    ls
    ;;

  glob)
    # Brace expansion feeds pathname expansion: each generated word is globbed on its own.
    cd "$2" || exit 1
    : >b1
    : >b2
    : >a1
    : >f1.txt
    args {b,a}*
    args f*.{txt,nomatch}
    ;;

  command-position)
    # A brace list as the command word builds a whole command line that contains no blank.
    eval '{echo,brace-ran}' 2>/dev/null
    echo "status=$?"
    ;;

  toggle)
    # The braceexpand option: present or not, and what turning it on and off does.
    # shellcheck disable=SC3040 # braceexpand is an extension; probing for it is the point
    if (set -o braceexpand) 2>/dev/null; then
      # shellcheck disable=SC3040 # the extension exists in this branch
      set -o braceexpand
      eval 'args {a,b} {1..3} {a..c}'
      # shellcheck disable=SC3040 # the extension exists in this branch
      set +o braceexpand
      eval 'args {a,b}'
    else
      echo "no braceexpand option"
      eval 'args {a,b}'
    fi
    ;;

  noglob)
    # set -f turns pathname expansion off; is brace expansion tied to it?
    set -f
    args {a,b}
    ;;

  posix-mode)
    # Does the shell's POSIX mode turn brace expansion off?
    # shellcheck disable=SC3040 # a posix option is an extension; probing for it is the point
    if (set -o posix) 2>/dev/null; then
      # shellcheck disable=SC3040 # the extension exists in this branch
      set -o posix
      eval 'args {a,b}'
    else
      echo "no posix option"
    fi
    ;;

  array-declare)
    # declare with a compound assignment: bash 3.2 brace expands the whole word too early.
    (eval 'declare -a arr=({1..3}); args "${arr[@]}"') 2>/dev/null
    echo "status=$?"
    ;;

  count)
    # The number of generated words is the product of the list lengths.
    set -- {a,b,c}{a,b,c}{a,b,c}{a,b,c}
    echo "$#"
    set -- {1..100000}
    echo "$#"
    ;;

  e2big)
    # One million words fit in the shell; execve refuses them as the arguments of an external program (env).
    set -- {1..1000000}
    echo "words=$#"
    /usr/bin/env true "$@" 2>/dev/null
    rc=$?
    echo "status=$rc"
    ;;

  ksh-format)
    # ksh93 accepts a printf format after the range.
    args {1..3%02d}
    ;;

  zsh-ccl)
    # zsh BRACE_CCL: a brace word with no comma becomes a sorted character class.
    if command -v setopt >/dev/null 2>&1; then
      setopt braceccl
      eval 'args {cba}'
    else
      echo "no setopt builtin"
    fi
    ;;

  *)
    echo "usage: brace-probe.sh MODE [DIR]" >&2
    exit 2
    ;;
esac
